// Letters with accents: base letter plus a mark above.
for (const [ch, base, mark] of [['é', 'e', 'acute'], ['á', 'a', 'acute'], ['ú', 'u', 'acute'], ['ó', 'o', 'acute'], ['í', 'i', 'acute']]) {
  const g = G[base].map((r) => r);
  const w = g[0].length, mid = Math.floor(w / 2);
  g[0] = '.'.repeat(w).split('').map((c, i) => (i === Math.min(w - 1, mid + 1) ? '#' : '.')).join('');
  g[1] = '.'.repeat(w).split('').map((c, i) => (i === mid ? '#' : '.')).join('');
  G[ch] = g;
}

const ENDS_LOW = new Set('acdehiklmnstuz'.split(''));
const STARTS_X = new Set('acdegijmnopqrsuvwxyz'.split(''));

function glyph(ch) { return G[ch] || G['?']; }

/** Width in pixels of text in a font, before scaling. */
export function measure(text, { hand = false } = {}) {
  let w = 0;
  for (const ch of text) w += glyph(ch)[0].length + 1;
  return Math.max(0, w - 1) + (hand ? 3 : 0);
}

/**
 * Draws text into a 2D context at art-pixel size. x, y: top-left of the cap height. color: CSS colour.
 * scale: whole-pixel scale (titles at 2). hand: the handwriting. seed: the handwriting's wobble.
 * Returns the width drawn.
 */
export function drawText(ctx, text, x, y, { color = '#efe6d6', scale = 1, hand = false, seed = 1, shadow = null } = {}) {
  let cx = x, s = seed, prev = null;
  const rnd = () => { s = (s * 16807) % 2147483647; return s / 2147483647; };
  // handwriting leans one pixel for every 3.5 rows of the drawn size, so it stays a smooth slope when enlarged
  const lean = (oy) => (hand ? Math.floor((6 * scale - oy) / 3.5) : 0);
  // one font pixel at row r (from the cap top): a block of scale by scale, each of its rows leant on its own
  const put = (px, r, py, c) => {
    ctx.fillStyle = c;
    for (let k = 0; k < scale; k++) ctx.fillRect(Math.round(px + lean(r * scale + k)), Math.round(py + k), scale, 1);
  };
  for (const ch of text) {
    const g = glyph(ch), w = g[0].length;
    const dy = hand ? (rnd() < 0.1 ? -1 : 0) * scale : 0;
    for (let r = 0; r < g.length; r++) for (let c = 0; c < w; c++) {
      if (g[r][c] !== '#') continue;
      if (shadow) put(cx + c * scale + scale, r, y + r * scale + dy + scale, shadow);
      put(cx + c * scale, r, y + r * scale + dy, color);
    }
    // handwriting joins a letter that ends at the foot to the next small letter
    if (hand && prev && ENDS_LOW.has(prev) && STARTS_X.has(ch)) put(cx - scale, 6, y + 6 * scale + dy, color);
    cx += (w + 1) * scale;
    prev = ch;
  }
  return cx - x - scale;
}

/** Splits text into lines no wider than maxW pixels (at scale 1). */
export function wrap(text, maxW, opts = {}) {
  const words = text.split(' '), lines = [];
  let line = '';
  for (const w of words) {
    const t = line ? line + ' ' + w : w;
    if (measure(t, opts) > maxW && line) { lines.push(line); line = w; } else line = t;
  }
  if (line) lines.push(line);
  return lines;
}

