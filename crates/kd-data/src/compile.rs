fn three(v: [f32; 3]) -> String {
    format!("{}, {}, {}", v[0], v[1], v[2])
}

fn air_table(s: &AirSrc) -> Vec<(String, String)> {
    vec![
        (
            "Channels".into(),
            format!(
                "{}, {} and {} nm",
                s.wavelengths_nm[0], s.wavelengths_nm[1], s.wavelengths_nm[2]
            ),
        ),
        ("Rayleigh depths".into(), three(s.rayleigh)),
        (
            "Aerosol".into(),
            format!("turbidity {}, exponent {}", s.turbidity, s.aerosol_exponent),
        ),
        ("Ozone depths".into(), three(s.ozone)),
        (
            "Sky light".into(),
            format!(
                "Rayleigh's share {}, the aerosol's {}; at sunset {}, fading over {}°",
                s.sky_rayleigh_share, s.sky_aerosol_share, s.horizon_sky, s.horizon_fade_deg
            ),
        ),
        (
            "Twilight, night".into(),
            format!(
                "to {}°, e every {}°, ozone {} air masses a degree; moon 1/{}, tint {}; starlight {}",
                s.twilight_end_deg,
                s.twilight_fall_deg,
                s.twilight_ozone_per_deg,
                s.moon_weakness,
                three(s.moon_tint),
                s.starlight
            ),
        ),
        (
            "Exposure, rods".into(),
            format!(
                "scale {}, power {}; colour fades from {} to {} of noon",
                s.exposure_scale, s.exposure_power, s.rods_start, s.rods_full
            ),
        ),
        (
            "Grade, haze".into(),
            format!(
                "chroma × {}; levels {}; mixes {}; g {}; heights {} and {} m",
                s.grade_chroma,
                three(s.haze_levels),
                three(s.haze_mixes),
                s.haze_g,
                s.aerosol_height_m,
                s.rayleigh_height_m
            ),
        ),
    ]
}

/// An entry's generated table, between its markers.
fn table_text(rows: &[(String, String)]) -> String {
    let mut t = format!("{TABLE_START}\n| | |\n|---|---|\n");
    for (k, v) in rows {
        t.push_str(&format!("| {k} | {} |\n", v.replace('|', "\\|")));
    }
    t.push_str(TABLE_END);
    t
}

/// A file with each entry's table made afresh: the old one replaced, or a new one put before the entry's block.
fn with_tables(text: &str, tables: &[(usize, String)]) -> String {
    let lines: Vec<&str> = text.lines().collect();
    let mut out: Vec<String> = Vec::new();
    let mut i = 0;
    let mut pending: Option<&String> = None;
    while i < lines.len() {
        let line = lines[i];
        if line.starts_with("## ") {
            pending = tables.iter().find(|(l, _)| *l == i + 1).map(|(_, t)| t);
        }
        if line.trim_end() == TABLE_START {
            // Drop the old table up to its end marker; the fresh one goes in its place.
            while i < lines.len() && lines[i].trim_end() != TABLE_END {
                i += 1;
            }
            i += 1;
            if let Some(t) = pending.take() {
                out.extend(t.lines().map(String::from));
            }
            continue;
        }
        if line.trim_end() == "```toml"
            && let Some(t) = pending.take()
        {
            out.extend(t.lines().map(String::from));
            out.push(String::new());
        }
        out.push(line.to_string());
        i += 1;
    }
    let mut s = out.join("\n");
    if text.ends_with('\n') {
        s.push('\n');
    }
    s
}

/// `data/INDEX.md`: one table a kind (A3.6).
fn index_text(index: &BTreeMap<Kind, Vec<(u16, String, String, String)>>) -> String {
    let mut s = String::from(
        "# Catalogue index\n\nGenerated by `kd catalog tables` from the entries' blocks (A3.6); edit the entries, never this file.\n",
    );
    for kind in Kind::ALL {
        let title = match kind {
            Kind::Colour => "Fixed colours",
            Kind::Look => "Looks",
            Kind::Light => "The air",
        };
        s.push_str(&format!(
            "\n## {title} (`{}`)\n\n| Number | Id | Name | Stage |\n|---|---|---|---|\n",
            kind.place()
        ));
        let mut rows = index.get(&kind).cloned().unwrap_or_default();
        rows.sort();
        for (n, id, name, stage) in rows {
            s.push_str(&format!("| {n} | `{id}` | {name} | {stage} |\n"));
        }
    }
    s
}

fn parse_lock(text: &str, problems: &mut Vec<Problem>) -> BTreeMap<String, KindLock> {
    let mut out: BTreeMap<String, KindLock> = BTreeMap::new();
    let table: toml::Table = match toml::from_str(text) {
        Ok(t) => t,
        Err(e) => {
            problems.push(at(LOCK_FILE, 1, e.message().to_string()));
            return out;
        }
    };
    for (kind, v) in table {
        if !Kind::ALL.iter().any(|k| k.name() == kind) {
            problems.push(at(LOCK_FILE, 1, format!("[{kind}] is not a kind of entry")));
            continue;
        }
        let mut lock = KindLock::default();
        let Some(t) = v.as_table() else {
            problems.push(at(LOCK_FILE, 1, format!("[{kind}] is not a table")));
            continue;
        };
        for (id, n) in t {
            if id == "retired" {
                for (rid, rn) in n.as_table().into_iter().flatten() {
                    match rn.as_integer().and_then(|x| u16::try_from(x).ok()) {
                        Some(x) => {
                            lock.retired.insert(rid.clone(), x);
                        }
                        None => problems.push(at(LOCK_FILE, 1, format!("{kind}.retired.{rid} is not a number"))),
                    }
                }
            } else {
                match n.as_integer().and_then(|x| u16::try_from(x).ok()) {
                    Some(x) => {
                        lock.live.insert(id.clone(), x);
                    }
                    None => problems.push(at(LOCK_FILE, 1, format!("{kind}.{id} is not a number"))),
                }
            }
        }
        // No number is given twice, live or retired.
        let mut numbers: Vec<u16> = lock.live.values().chain(lock.retired.values()).copied().collect();
        numbers.sort_unstable();
        if numbers.windows(2).any(|w| w[0] == w[1]) {
            problems.push(at(LOCK_FILE, 1, format!("[{kind}] gives a number twice")));
        }
        out.insert(kind, lock);
    }
    out
}

fn lock_text(locks: &BTreeMap<String, KindLock>) -> String {
    let mut s = String::from(
        "# Permanent numbers of every catalogue entry, per kind (A3.6), written by `kd catalog build --assign`, never by\n\
         # hand. A removed entry's number stays, under its kind's `retired` table, and no number is ever given twice.\n",
    );
    for (kind, lock) in locks {
        if lock.live.is_empty() && lock.retired.is_empty() {
            continue;
        }
        s.push_str(&format!("\n[{kind}]\n"));
        let mut live: Vec<(&String, &u16)> = lock.live.iter().collect();
        live.sort_by_key(|(_, n)| **n);
        for (id, n) in live {
            s.push_str(&format!("{id} = {n}\n"));
        }
        if !lock.retired.is_empty() {
            s.push_str(&format!("\n[{kind}.retired]\n"));
            for (id, n) in &lock.retired {
                s.push_str(&format!("{id} = {n}\n"));
            }
        }
    }
    s
}

