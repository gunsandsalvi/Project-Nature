/// A surface's looks resolved to their numbers (rule 4) and its split checked: one to three looks, a split noise
/// of falling periods and rising take-over values between −1 and 1, one fewer than its looks.
fn surface_of(s: &SurfaceSrc, e: &Entry, looks: &[(u16, Look)], problems: &mut Vec<Problem>) -> Surface {
    let mut bad = |what: String| problems.push(at(&e.path, e.block_line, format!("{}: {what}", s.id)));
    if !(1..=3).contains(&s.looks.len()) {
        bad(format!("{} looks; a surface has 1 to 3 (A11.5)", s.looks.len()));
    }
    let mut look_number = |id: &String| {
        let n = looks.iter().find(|l| &l.1.id == id).map(|l| l.0);
        if n.is_none() {
            bad(format!("look {id:?} is not a look in {}", Kind::Look.place()));
        }
        n
    };
    let numbers: Vec<u16> = s.looks.iter().filter_map(&mut look_number).collect();
    let stone_look = s.stone_look.as_ref().and_then(&mut look_number);
    let tuft_looks: Vec<u16> = s.tuft_looks.iter().filter_map(&mut look_number).collect();
    if (1..s.looks.len()).any(|i| s.looks[..i].contains(&s.looks[i])) {
        bad("names a look twice".into());
    }
    let many = s.looks.len() > 1;
    if many == s.split_m.is_empty() {
        bad("a split noise's octaves come with more than one look, and only then".into());
    }
    if !s.split_m.iter().all(|&p| p > 0.0) || s.split_m.windows(2).any(|w| w[1] >= w[0]) {
        bad("the split's octaves are positive periods, each smaller than the last".into());
    }
    if s.split_at.len() + 1 != s.looks.len().max(1)
        || !s.split_at.iter().all(|v| (-1.0..=1.0).contains(v))
        || s.split_at.windows(2).any(|w| w[1] <= w[0])
    {
        bad("the split has one take-over value fewer than its looks, rising within −1 to 1".into());
    }
    let [smallest, largest] = s.relief_m;
    if !(smallest > 0.0 && smallest <= largest && largest <= 16.0 && largest < 16.0 * smallest) {
        bad("the relief's wavelengths run from a smallest to a largest within 16 m, at most four octaves".into());
    }
    if !(0.0..=1.0).contains(&s.relief_tilt) {
        bad("the relief's tilt is a slope from 0 to 1".into());
    }
    if !(0.0..=8.0).contains(&s.stones_per_m2) || !(0.0..=8.0).contains(&s.tufts_per_m2) {
        bad("its stones and tufts number 0 to 8 a square metre".into());
    }
    if (s.stones_per_m2 > 0.0) != s.stone_look.is_some() {
        bad("stones come with the look they are drawn in, and only then".into());
    }
    if (s.tufts_per_m2 > 0.0) == s.tuft_looks.is_empty()
        || !(s.tuft_looks.len() <= 1 || s.tuft_looks.len() == s.looks.len())
    {
        bad("tufts come with one look, or one for each of the surface's looks, and only then".into());
    }
    Surface {
        id: s.id.clone(),
        name: s.name.clone(),
        number: 0,
        looks: numbers,
        split_m: s.split_m.clone(),
        split_at: s.split_at.clone(),
        rock: s.rock,
        relief_m: s.relief_m,
        relief_tilt: s.relief_tilt,
        stones_per_m2: s.stones_per_m2,
        stone_look,
        tufts_per_m2: s.tufts_per_m2,
        tuft_looks,
    }
}

/// Words in a list: "a", "a and b", "a, b and c".
fn and_list(words: &[String]) -> String {
    match words {
        [] => String::new(),
        [one] => one.clone(),
        [rest @ .., last] => format!("{} and {last}", rest.join(", ")),
    }
}

fn surface_table(s: &Surface, name_of: &dyn Fn(u16) -> String) -> Vec<(String, String)> {
    let numbers = |v: &[f32]| and_list(&v.iter().map(f32::to_string).collect::<Vec<_>>());
    vec![
        (
            "Looks".into(),
            and_list(&s.looks.iter().map(|&n| name_of(n)).collect::<Vec<_>>()),
        ),
        (
            "Split".into(),
            if s.split_m.is_empty() {
                "none".into()
            } else {
                format!(
                    "a noise of {} m octaves; the next look above {}",
                    numbers(&s.split_m),
                    numbers(&s.split_at)
                )
            },
        ),
        ("Draws as rock".into(), if s.rock { "yes" } else { "no" }.into()),
        (
            "Relief".into(),
            format!(
                "{} to {} m across, each octave tilting the ground by up to {}",
                s.relief_m[0], s.relief_m[1], s.relief_tilt
            ),
        ),
        ("Cover".into(), cover_words(s, name_of)),
    ]
}

/// The cover row's words: stones and tufts a square metre and their looks' names.
fn cover_words(s: &Surface, names: &dyn Fn(u16) -> String) -> String {
    let mut parts = Vec::new();
    if let Some(look) = s.stone_look.filter(|_| s.stones_per_m2 > 0.0) {
        parts.push(format!(
            "stones, {} a square metre, in {}",
            s.stones_per_m2,
            names(look)
        ));
    }
    if s.tufts_per_m2 > 0.0 {
        let looks: Vec<String> = s.tuft_looks.iter().map(|&l| names(l)).collect();
        parts.push(format!(
            "tufts, {} a square metre, in {}",
            s.tufts_per_m2,
            and_list(&looks)
        ));
    }
    if parts.is_empty() {
        "none".into()
    } else {
        parts.join("; ")
    }
}

