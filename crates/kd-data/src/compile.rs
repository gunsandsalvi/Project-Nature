#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct VersionSrc {
    major: u16,
    minor: u16,
    generator: u16,
}

/// The numbers of one kind in `data/ids.lock`: live ids and retired ones.
#[derive(Clone, Debug, Default)]
struct KindLock {
    live: BTreeMap<String, u16>,
    retired: BTreeMap<String, u16>,
}

impl KindLock {
    fn next(&self) -> u16 {
        self.live
            .values()
            .chain(self.retired.values())
            .map(|&n| n + 1)
            .max()
            .unwrap_or(0)
    }
}

/// Compiles the sources: `assign` gives new entries their numbers. Hard problems fail; stale generated parts come
/// back in `Output::stale`.
pub fn compile(sources: &[Source], assign: bool) -> Result<Output, Vec<Problem>> {
    let mut problems = Vec::new();
    let mut sorted: Vec<&Source> = sources.iter().collect();
    sorted.sort_by(|a, b| a.path.cmp(&b.path));
    let find = |path: &str| sorted.iter().find(|s| s.path == path).map(|s| s.text.as_str());

    let versions = match find(VERSION_FILE).map(toml::from_str::<VersionSrc>) {
        Some(Ok(v)) => Versions {
            major: v.major,
            minor: v.minor,
            generator: v.generator,
        },
        Some(Err(e)) => {
            problems.push(at(VERSION_FILE, 1, e.message().to_string()));
            Versions::default()
        }
        None => {
            problems.push(at(
                VERSION_FILE,
                1,
                "missing: it holds major, minor and generator (A3.6)".into(),
            ));
            Versions::default()
        }
    };
    let mut locks = parse_lock(find(LOCK_FILE).unwrap_or(""), &mut problems);

    // Every entries file, split into entries.
    let mut by_kind: BTreeMap<Kind, Vec<Entry>> = BTreeMap::new();
    let mut files: Vec<(&Source, Kind)> = Vec::new();
    for s in &sorted {
        if !s.path.ends_with(".md") {
            continue;
        }
        match role(&s.path) {
            FileRole::Entries(kind) => {
                files.push((s, kind));
                by_kind.entry(kind).or_default().extend(entries(s, &mut problems));
            }
            FileRole::Unclaimed => problems.push(at(&s.path, 1, "no kind of entry claims this file (A3.6)".into())),
            FileRole::Other => {}
        }
    }

    // Each kind's entries parsed, checked, numbered and compiled.
    let mut colours: Vec<(u16, Colour)> = Vec::new();
    let mut looks: Vec<(u16, Look)> = Vec::new();
    let mut airs: Vec<(u16, Air)> = Vec::new();
    let mut tables: BTreeMap<String, Vec<(usize, String)>> = BTreeMap::new();
    let mut index: BTreeMap<Kind, Vec<(u16, String, String, String)>> = BTreeMap::new();
    let mut count = 0;
    for kind in Kind::ALL {
        let lock = locks.entry(kind.name().to_string()).or_default();
        let mut seen: BTreeMap<String, usize> = BTreeMap::new();
        for e in by_kind.remove(&kind).unwrap_or_default() {
            count += 1;
            let compiled = match kind {
                Kind::Colour => parse::<ColourSrc>(&e, &mut problems).map(|s| {
                    let head = head(&s.id, &s.name, &s.stage, &s.checks);
                    let rgb = colour(&s.value).unwrap_or_else(|| {
                        problems.push(at(&e.path, e.block_line, format!("value {:?} is not #rrggbb", s.value)));
                        [0; 3]
                    });
                    if s.use_.trim().is_empty() {
                        problems.push(at(
                            &e.path,
                            e.block_line,
                            "a fixed colour says what it is used for".into(),
                        ));
                    }
                    let table = vec![
                        ("Value".to_string(), hex(rgb)),
                        ("Use".to_string(), s.use_.trim().to_string()),
                    ];
                    (
                        head,
                        table,
                        Compiled::Colour(Colour {
                            id: s.id.clone(),
                            name: s.name.clone(),
                            number: 0,
                            rgb,
                        }),
                    )
                }),
                Kind::Look => parse::<LookSrc>(&e, &mut problems).map(|s| {
                    let head = head(&s.id, &s.name, &s.stage, &s.checks);
                    let rgb = colour(&s.colour).unwrap_or_else(|| {
                        problems.push(at(
                            &e.path,
                            e.block_line,
                            format!("colour {:?} is not #rrggbb", s.colour),
                        ));
                        [0; 3]
                    });
                    if !(4..=7).contains(&s.steps) {
                        problems.push(at(
                            &e.path,
                            e.block_line,
                            format!("{} steps: a look has 4 to 7 (PRE-20)", s.steps),
                        ));
                    }
                    let sheen = s.sheen.unwrap_or(0.0);
                    if !(0.0..=1.0).contains(&sheen) {
                        problems.push(at(&e.path, e.block_line, format!("sheen {sheen} is outside 0–1")));
                    }
                    let glow = s.glow.as_deref().map(|g| {
                        colour(g).unwrap_or_else(|| {
                            problems.push(at(&e.path, e.block_line, format!("glow {g:?} is not #rrggbb")));
                            [0; 3]
                        })
                    });
                    let table = vec![
                        ("Colour under white light".to_string(), hex(rgb)),
                        ("Steps".to_string(), s.steps.to_string()),
                        (
                            "Sheen".to_string(),
                            if sheen > 0.0 { sheen.to_string() } else { "none".into() },
                        ),
                        ("Glow".to_string(), glow.map(hex).unwrap_or_else(|| "none".into())),
                    ];
                    let entry = Look {
                        id: s.id.clone(),
                        name: s.name.clone(),
                        number: 0,
                        rgb,
                        steps: s.steps,
                        sheen,
                        glow,
                    };
                    (head, table, Compiled::Look(entry))
                }),
                Kind::Light => parse::<AirSrc>(&e, &mut problems).map(|s| {
                    check_air(&s, &e, &mut problems);
                    (
                        head(&s.id, &s.name, &s.stage, &s.checks),
                        air_table(&s),
                        Compiled::Air(air_of(&s)),
                    )
                }),
            };
            let Some((head, table, entry)) = compiled else { continue };
            // Rules 2 and 6: the id, the name, the stage and the checks.
            check_head(&head, &e, &mut problems);
            if let Some(first) = seen.insert(head.id.clone(), e.line) {
                problems.push(at(
                    &e.path,
                    e.line,
                    format!("id {} is used twice (first on line {first})", head.id),
                ));
                continue;
            }
            let number = if let Some(&n) = lock.live.get(&head.id) {
                n
            } else if lock.retired.contains_key(&head.id) {
                problems.push(at(
                    &e.path,
                    e.line,
                    format!("id {} is retired and may not come back", head.id),
                ));
                continue;
            } else if assign {
                let n = lock.next();
                lock.live.insert(head.id.clone(), n);
                n
            } else {
                problems.push(at(
                    &e.path,
                    e.line,
                    format!("id {} has no number: kd catalog build --assign", head.id),
                ));
                continue;
            };
            tables
                .entry(e.path.clone())
                .or_default()
                .push((e.line, table_text(&table)));
            index
                .entry(kind)
                .or_default()
                .push((number, head.id.clone(), head.name.clone(), head.stage.clone()));
            match entry {
                Compiled::Colour(c) => colours.push((number, Colour { number, ..c })),
                Compiled::Look(l) => looks.push((number, Look { number, ..l })),
                Compiled::Air(a) => airs.push((number, a)),
            }
        }
    }

    // Kind-wide rules: there is exactly one air, and the palette holds every colour. That fixed colour 0 is void,
    // palette index 0, the renderer's tests check, since rules here never name an entry (A2.3 rule 5).
    colours.sort_by_key(|c| c.0);
    looks.sort_by_key(|l| l.0);
    if airs.len() != 1 {
        problems.push(at(
            Kind::Light.place(),
            1,
            format!("{} entries of air; there is exactly one (A11.4)", airs.len()),
        ));
    }
    if colours.len() + looks.len() > 256 {
        problems.push(at(
            Kind::Look.place(),
            1,
            "more than 255 colours besides void (A11.3)".into(),
        ));
    }
    if !problems.is_empty() {
        return Err(problems);
    }

    let catalogue = Catalogue {
        versions,
        colours: colours.into_iter().map(|c| c.1).collect(),
        looks: looks.into_iter().map(|l| l.1).collect(),
        air: airs.remove(0).1,
    };
    let mut stale = Vec::new();
    for (s, _) in &files {
        let fresh = with_tables(&s.text, tables.get(&s.path).map(Vec::as_slice).unwrap_or(&[]));
        if fresh != s.text {
            stale.push((s.path.clone(), fresh));
        }
    }
    let fresh_index = index_text(&index);
    if find(INDEX_FILE) != Some(fresh_index.as_str()) {
        stale.push((INDEX_FILE.to_string(), fresh_index));
    }
    Ok(Output {
        blob: blob::encode(&catalogue),
        catalogue,
        lock: lock_text(&locks),
        stale,
        entries: count,
    })
}

enum Compiled {
    Colour(Colour),
    Look(Look),
    Air(Air),
}

/// The fields every entry has (A3.6).
struct Head {
    id: String,
    name: String,
    stage: String,
    checks: Vec<String>,
}

fn head(id: &str, name: &str, stage: &str, checks: &[String]) -> Head {
    Head {
        id: id.into(),
        name: name.into(),
        stage: stage.into(),
        checks: checks.to_vec(),
    }
}

fn at(path: &str, line: usize, message: String) -> Problem {
    Problem {
        path: path.to_string(),
        line,
        message,
    }
}

/// A file's entries: its `##` headings, each with exactly one `toml` block (rule 1); the file opens with a `#` title.
fn entries(s: &Source, problems: &mut Vec<Problem>) -> Vec<Entry> {
    let lines: Vec<&str> = s.text.lines().collect();
    if !lines
        .iter()
        .find(|l| !l.trim().is_empty())
        .is_some_and(|l| l.starts_with("# "))
    {
        problems.push(at(
            &s.path,
            1,
            "a catalogue file opens with a # title and a short introduction".into(),
        ));
    }
    let mut out = Vec::new();
    let heads: Vec<usize> = (0..lines.len()).filter(|&i| lines[i].starts_with("## ")).collect();
    for (k, &h) in heads.iter().enumerate() {
        let end = heads.get(k + 1).copied().unwrap_or(lines.len());
        let mut blocks = Vec::new();
        let mut i = h + 1;
        while i < end {
            if lines[i].trim_end() == "```toml" {
                let start = i + 1;
                let mut j = start;
                while j < end && lines[j].trim_end() != "```" {
                    j += 1;
                }
                blocks.push((start, lines[start..j.min(end)].join("\n")));
                i = j + 1;
            } else {
                i += 1;
            }
        }
        let heading = lines[h][3..].trim().to_string();
        match blocks.len() {
            1 => {
                let (start, block) = blocks.remove(0);
                out.push(Entry {
                    path: s.path.clone(),
                    heading,
                    line: h + 1,
                    block,
                    block_line: start + 1,
                });
            }
            n => problems.push(at(
                &s.path,
                h + 1,
                format!("{heading}: {n} toml blocks; an entry has exactly one"),
            )),
        }
    }
    out
}

/// An entry's block in its kind's schema, or the parser's problem at its line (rule 1).
fn parse<T: DeserializeOwned>(e: &Entry, problems: &mut Vec<Problem>) -> Option<T> {
    match toml::from_str::<T>(&e.block) {
        Ok(t) => Some(t),
        Err(err) => {
            let line = err
                .span()
                .map_or(0, |r| e.block[..r.start.min(e.block.len())].matches('\n').count());
            problems.push(at(
                &e.path,
                e.block_line + line,
                format!("{}: {}", e.heading, err.message().trim()),
            ));
            None
        }
    }
}

/// Rule 2 and rule 6: the id is snake_case, the name is the heading, the stage a milestone, and the checks name
/// at least one ID.
fn check_head(h: &Head, e: &Entry, problems: &mut Vec<Problem>) {
    let snake = h.id.chars().next().is_some_and(|c| c.is_ascii_lowercase())
        && h.id
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    if !snake {
        problems.push(at(&e.path, e.line, format!("id {:?} is not snake_case", h.id)));
    }
    if h.name != e.heading {
        problems.push(at(
            &e.path,
            e.line,
            format!("name {:?} is not the heading {:?}", h.name, e.heading),
        ));
    }
    let milestone = h.stage.len() == 6
        && h.stage.starts_with("MIL-0")
        && h.stage[5..].parse::<u8>().is_ok_and(|n| (1..=7).contains(&n));
    if !milestone {
        problems.push(at(
            &e.path,
            e.line,
            format!("stage {:?} is not a milestone, MIL-01 to MIL-07", h.stage),
        ));
    }
    let is_id = |c: &str| {
        let (area, num) = c.split_at(c.find('-').unwrap_or(0));
        area.len() == 3
            && area.chars().all(|x| x.is_ascii_uppercase())
            && (3..=4).contains(&num.len())
            && num[1..].chars().all(|x| x.is_ascii_digit())
    };
    if h.checks.is_empty() {
        problems.push(at(&e.path, e.line, format!("{} names no checks (MAT-17)", h.id)));
    }
    for c in h.checks.iter().filter(|c| !is_id(c)) {
        problems.push(at(&e.path, e.line, format!("checks holds {c:?}, not an ID")));
    }
}

/// `#rrggbb` as three bytes.
fn colour(s: &str) -> Option<[u8; 3]> {
    let hex = s
        .strip_prefix('#')
        .filter(|h| h.len() == 6 && h.chars().all(|c| c.is_ascii_hexdigit()))?;
    let byte = |i: usize| u8::from_str_radix(&hex[i..i + 2], 16).ok();
    Some([byte(0)?, byte(2)?, byte(4)?])
}

fn hex(c: [u8; 3]) -> String {
    format!("#{:02x}{:02x}{:02x}", c[0], c[1], c[2])
}

fn check_air(s: &AirSrc, e: &Entry, problems: &mut Vec<Problem>) {
    let mut bad = |what: &str| problems.push(at(&e.path, e.block_line, format!("air: {what}")));
    if !(0.0..=1.0).contains(&s.turbidity) {
        bad("turbidity outside 0–1");
    }
    if !(s.twilight_end_deg < 0.0 && s.twilight_fall_deg > 0.0) {
        bad("twilight ends below the horizon and falls by e over a positive number of degrees");
    }
    if !(s.rods_full < s.rods_start && s.rods_start < 1.0 && s.rods_full > 0.0) {
        bad("rod vision starts above where it is full, both below noon's light");
    }
    if !(s.haze_levels[0] < s.haze_levels[1] && s.haze_levels[1] < s.haze_levels[2] && s.haze_levels[2] < 1.0) {
        bad("haze levels rise below 1");
    }
    if !(s.haze_mixes.iter().all(|&m| (0.0..=1.0).contains(&m)) && s.haze_mixes[0] < s.haze_mixes[2]) {
        bad("haze mixes lie in 0–1 and rise");
    }
    if !(0.0..1.0).contains(&s.haze_g) || s.grade_chroma < 1.0 || s.exposure_power <= 0.0 || s.moon_weakness <= 1.0 {
        bad("g in 0–1, the grade at least 1, exposure's power and the moon's weakness positive");
    }
}

