//! The catalogue compiler (A3.6), behind feature `compile`; `kd catalog`, `kd-tools` at start and `kd-app`'s build
//! script run it. It takes the files' texts from its caller and reads no file itself: every `data/**/*.md` in sorted
//! path order is split at its `##` headings, each entry's one `toml` block parsed into its kind's schema with no
//! unknown or missing field, its id resolved to its number in `data/ids.lock`, and the entries put in number order
//! and encoded as the blob. Rules 1, 2, 4 and 6 of A3.6's validation hold for the kinds so far.
//!
//! Implements MAT-17, see A3.6: every entry names its checks, and an entry that breaks a rule fails with its file
//! and line.

use core::fmt;
use std::collections::BTreeMap;

use serde::Deserialize;
use serde::de::DeserializeOwned;

use crate::blob;
use crate::kinds::{FileRole, Kind, role};
use crate::schema::{Air, Catalogue, Colour, Look, Versions};

pub const VERSION_FILE: &str = "data/VERSION.toml";
pub const LOCK_FILE: &str = "data/ids.lock";
pub const INDEX_FILE: &str = "data/INDEX.md";
pub const TABLE_START: &str = "<!-- table: generated by `kd catalog tables`; edit the block, not the table -->";
pub const TABLE_END: &str = "<!-- end table -->";

/// A file under `data/`: its path from the repository's root, with `/` between parts, and its text.
#[derive(Clone, Debug)]
pub struct Source {
    pub path: String,
    pub text: String,
}

/// A problem, where it is.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Problem {
    pub path: String,
    pub line: usize,
    pub message: String,
}

impl fmt::Display for Problem {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}:{}: {}", self.path, self.line, self.message)
    }
}

/// What compiling gives.
#[derive(Clone, Debug)]
pub struct Output {
    pub catalogue: Catalogue,
    pub blob: Vec<u8>,
    /// `data/ids.lock` as it now reads: with `assign`, new entries have their numbers.
    pub lock: String,
    /// Each file whose generated parts (the entries' tables, the index) differ from what the blocks give, with its
    /// text made afresh; `kd catalog tables` writes them, and `kd catalog check` fails while any is listed.
    pub stale: Vec<(String, String)>,
    pub entries: usize,
}

/// One entry as written: its heading, its line, its block and the lines its table and block hold.
struct Entry {
    path: String,
    heading: String,
    line: usize,
    block: String,
    block_line: usize,
}

