fn parse_lock(text: &str, problems: &mut Vec<Problem>) -> BTreeMap<String, KindLock> {
    let mut out: BTreeMap<String, KindLock> = BTreeMap::new();
    let table: toml::Table = match toml::from_str(text) {
        Ok(t) => t,
        Err(e) => {
            problems.push(at(LOCK_FILE, 1, e.message().to_string()));
            return out;
        }
    };
    for (kind, v) in table {
        if !Kind::ALL.iter().any(|k| k.name() == kind) {
            problems.push(at(LOCK_FILE, 1, format!("[{kind}] is not a kind of entry")));
            continue;
        }
        let mut lock = KindLock::default();
        let Some(t) = v.as_table() else {
            problems.push(at(LOCK_FILE, 1, format!("[{kind}] is not a table")));
            continue;
        };
        for (id, n) in t {
            if id == "retired" {
                for (rid, rn) in n.as_table().into_iter().flatten() {
                    match rn.as_integer().and_then(|x| u16::try_from(x).ok()) {
                        Some(x) => {
                            lock.retired.insert(rid.clone(), x);
                        }
                        None => problems.push(at(LOCK_FILE, 1, format!("{kind}.retired.{rid} is not a number"))),
                    }
                }
            } else {
                match n.as_integer().and_then(|x| u16::try_from(x).ok()) {
                    Some(x) => {
                        lock.live.insert(id.clone(), x);
                    }
                    None => problems.push(at(LOCK_FILE, 1, format!("{kind}.{id} is not a number"))),
                }
            }
        }
        // No number is given twice, live or retired.
        let mut numbers: Vec<u16> = lock.live.values().chain(lock.retired.values()).copied().collect();
        numbers.sort_unstable();
        if numbers.windows(2).any(|w| w[0] == w[1]) {
            problems.push(at(LOCK_FILE, 1, format!("[{kind}] gives a number twice")));
        }
        out.insert(kind, lock);
    }
    out
}

fn lock_text(locks: &BTreeMap<String, KindLock>) -> String {
    let mut s = String::from(
        "# Permanent numbers of every catalogue entry, per kind (A3.6), written by `kd catalog build --assign`, never by\n\
         # hand. A removed entry's number stays, under its kind's `retired` table, and no number is ever given twice.\n",
    );
    for (kind, lock) in locks {
        if lock.live.is_empty() && lock.retired.is_empty() {
            continue;
        }
        s.push_str(&format!("\n[{kind}]\n"));
        let mut live: Vec<(&String, &u16)> = lock.live.iter().collect();
        live.sort_by_key(|(_, n)| **n);
        for (id, n) in live {
            s.push_str(&format!("{id} = {n}\n"));
        }
        if !lock.retired.is_empty() {
            s.push_str(&format!("\n[{kind}.retired]\n"));
            for (id, n) in &lock.retired {
                s.push_str(&format!("{id} = {n}\n"));
            }
        }
    }
    s
}

