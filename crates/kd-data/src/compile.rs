/// An entry's generated table, between its markers.
fn table_text(rows: &[(String, String)]) -> String {
    let mut t = format!("{TABLE_START}\n| | |\n|---|---|\n");
    for (k, v) in rows {
        t.push_str(&format!("| {k} | {} |\n", v.replace('|', "\\|")));
    }
    t.push_str(TABLE_END);
    t
}

/// A file with each entry's table made afresh: the old one replaced, or a new one put before the entry's block.
fn with_tables(text: &str, tables: &[(usize, String)]) -> String {
    let lines: Vec<&str> = text.lines().collect();
    let mut out: Vec<String> = Vec::new();
    let mut i = 0;
    let mut pending: Option<&String> = None;
    while i < lines.len() {
        let line = lines[i];
        if line.starts_with("## ") {
            pending = tables.iter().find(|(l, _)| *l == i + 1).map(|(_, t)| t);
        }
        if line.trim_end() == TABLE_START {
            // Drop the old table up to its end marker; the fresh one goes in its place.
            while i < lines.len() && lines[i].trim_end() != TABLE_END {
                i += 1;
            }
            i += 1;
            if let Some(t) = pending.take() {
                out.extend(t.lines().map(String::from));
            }
            continue;
        }
        if line.trim_end() == "```toml"
            && let Some(t) = pending.take()
        {
            out.extend(t.lines().map(String::from));
            out.push(String::new());
        }
        out.push(line.to_string());
        i += 1;
    }
    let mut s = out.join("\n");
    if text.ends_with('\n') {
        s.push('\n');
    }
    s
}

