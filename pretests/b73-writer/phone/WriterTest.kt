    /** Blocking: call from a worker thread. Returns the result as JSON (about 15 KB with the 20 texts). */
    @JvmStatic
    @JvmOverloads
    fun run(context: Context, budgetMs: Long = 270_000L): JSONObject =
        runBlocking { runAll(context.applicationContext, budgetMs) }

    private fun now() = SystemClock.elapsedRealtime()

    private suspend fun runAll(ctx: Context, budgetMs: Long): JSONObject {
        val t0 = now()
        val deadline = t0 + budgetMs
        val out = JSONObject().put("b73", VERSION).put("api", "mlkit genai-prompt 1.0.0-beta4")
            .put("device", deviceInfo(ctx)).put("before", vitals(ctx))
        val passes = JSONArray()
        out.put("passes", passes)
        // FULL is the main test. FAST (a lighter variant, if the phone has it) only uses time that is left over.
        passes.put(runPass(ctx, ModelPreference.FULL, "FULL", deadline, allowDownload = true))
        if (deadline - now() > 60_000) {
            passes.put(runPass(ctx, ModelPreference.FAST, "FAST", deadline, allowDownload = false))
        } else {
            passes.put(JSONObject().put("preference", "FAST").put("skipped", "no time left"))
        }
        return out.put("after", vitals(ctx)).put("wall_ms", now() - t0)
    }

    private suspend fun runPass(ctx: Context, pref: Int, name: String, deadline: Long, allowDownload: Boolean): JSONObject {
        val pass = JSONObject().put("preference", name)
        val model = try {
            Generation.getClient(generationConfig {
                modelConfig = modelConfig {
                    releaseStage = ModelReleaseStage.STABLE
                    preference = pref
                }
            })
        } catch (t: Throwable) {
            return pass.put("status", "client_error").put("error", t.toString().take(200))
        }
        try {
            var status = model.checkStatus()
            pass.put("status_at_start", statusName(status))
            if (status == FeatureStatus.DOWNLOADABLE && allowDownload) {
                pass.put("download", download(model, minOf(deadline, now() + 90_000)))
                status = model.checkStatus()
            }
            val waitUntil = minOf(deadline, now() + 60_000)
            while (status == FeatureStatus.DOWNLOADING && now() < waitUntil) {
                delay(5_000)
                status = model.checkStatus()
            }
            pass.put("status", statusName(status))
            if (status != FeatureStatus.AVAILABLE) return pass
            pass.put("base_model", runCatching { model.getBaseModelName() }.getOrElse { "error: $it".take(120) })
            pass.put("token_limit", runCatching { model.getTokenLimit() }.getOrElse { -1 })
            val w0 = now()
            val warm = runCatching { model.warmup() }
            pass.put("warmup_ms", now() - w0).put("warmup_ok", warm.isSuccess)
            val runs = JSONArray()
            pass.put("runs", runs)
            for (p in PROMPTS) {
                val left = deadline - now()
                if (left < 15_000) {
                    pass.put("stopped", "time budget")
                    break
                }
                val r = runOne(model, p, minOf(60_000L, left))
                r.put("battery_c", batteryTempC(ctx)).put("thermal", thermalStatus(ctx))
                runs.put(r)
                val code = r.optString("error_code")
                if (code in STOP_CODES) {
                    pass.put("stopped", code)
                    break
                }
            }
            pass.put("summary", summary(runs))
        } catch (t: Throwable) {
            pass.put("error", t.toString().take(200))
        } finally {
            runCatching { model.close() }
        }
        return pass
    }

    private val STOP_CODES = setOf("BACKGROUND_USE_BLOCKED", "PER_APP_BATTERY_USE_QUOTA_EXCEEDED", "NOT_AVAILABLE",
        "NEEDS_SYSTEM_UPDATE", "AICORE_INCOMPATIBLE", "NOT_SUPPORTED")

    private suspend fun download(model: GenerativeModel, until: Long): JSONObject {
        val d = JSONObject()
        val t0 = now()
        val finished = withTimeoutOrNull(maxOf(1L, until - now())) {
            model.download().collect { s ->
                when (s) {
                    is DownloadStatus.DownloadStarted -> d.put("bytes_to_download", s.bytesToDownload)
                    is DownloadStatus.DownloadProgress -> d.put("bytes_done", s.totalBytesDownloaded)
                    is DownloadStatus.DownloadCompleted -> d.put("completed", true)
                    is DownloadStatus.DownloadFailed ->
                        d.put("failed", errorName(s.e.errorCode)).put("error", s.e.message?.take(200))
                }
            }
            true
        }
        return d.put("waited_ms", now() - t0).put("finished_waiting", finished == true)
    }

    private suspend fun runOne(model: GenerativeModel, p: Prompt, timeoutMs: Long): JSONObject {
        val r = JSONObject().put("id", p.id).put("voice", p.voice).put("dark", p.dark)
        val start = now()
        val first = AtomicLong(-1L)
        val streamed = StringBuffer()
        val request = generateContentRequest(TextPart(p.text)) {
            temperature = 0.3f
            topK = 20
            seed = 73
            candidateCount = 1
            maxOutputTokens = 256
        }
        val callback = object : StreamingCallback {
            override fun onNewText(text: String) {
                if (text.isNotBlank()) first.compareAndSet(-1L, now())
                streamed.append(text)
            }
        }
        try {
            val resp = withTimeoutOrNull(timeoutMs) { model.generateContent(request, callback) }
            val end = now()
            val cand = resp?.candidates?.firstOrNull()
            val text = (cand?.text ?: streamed.toString()).trim()
            val words = text.split(Regex("\\s+")).count { it.isNotEmpty() }
            val firstAt = if (first.get() > 0) first.get() else end
            r.put("ttfw_ms", firstAt - start).put("total_ms", end - start).put("words", words)
                .put("wps", if (end > firstAt) round2(words * 1000.0 / (end - firstAt)) else JSONObject.NULL)
                .put("wps_all", round2(words * 1000.0 / maxOf(1L, end - start)))
                .put("finish", finishName(cand?.finishReason)).put("text", text)
            if (resp == null) r.put("error_code", "TIMEOUT")
        } catch (e: GenAiException) {
            r.put("error_code", errorName(e.errorCode)).put("error", e.message?.take(200))
                .put("total_ms", now() - start).put("text", streamed.toString().trim())
        } catch (t: Throwable) {
            r.put("error_code", "EXCEPTION").put("error", t.toString().take(200)).put("total_ms", now() - start)
        }
        return r
    }

    private fun summary(runs: JSONArray): JSONObject {
        val ok = (0 until runs.length()).map { runs.getJSONObject(it) }.filter { !it.has("error_code") }
        fun median(xs: List<Double>) = if (xs.isEmpty()) JSONObject.NULL else xs.sorted()[xs.size / 2]
        return JSONObject().put("done", ok.size).put("tried", runs.length())
            .put("median_ttfw_ms", median(ok.map { it.optDouble("ttfw_ms") }))
            .put("median_wps", median(ok.mapNotNull { if (it.isNull("wps")) null else it.optDouble("wps") }))
            .put("max_total_ms", ok.maxOfOrNull { it.optLong("total_ms") } ?: JSONObject.NULL)
            .put("words", ok.sumOf { it.optInt("words") })
    }

    private fun round2(x: Double) = Math.round(x * 100) / 100.0

    private fun statusName(s: Int) = when (s) {
        FeatureStatus.AVAILABLE -> "available"
        FeatureStatus.DOWNLOADABLE -> "downloadable"
        FeatureStatus.DOWNLOADING -> "downloading"
        FeatureStatus.UNAVAILABLE -> "unavailable"
        else -> "unknown($s)"
    }

    private fun finishName(f: Int?) = when (f) {
        null -> "none"
        Candidate.FinishReason.STOP -> "stop"
        Candidate.FinishReason.MAX_TOKENS -> "max_tokens"
        else -> "other($f)"
    }

    private fun errorName(c: Int) = when (c) {
        GenAiException.ErrorCode.BUSY -> "BUSY"
        GenAiException.ErrorCode.CANCELLED -> "CANCELLED"
        GenAiException.ErrorCode.NOT_AVAILABLE -> "NOT_AVAILABLE"
        GenAiException.ErrorCode.REQUEST_TOO_LARGE -> "REQUEST_TOO_LARGE"
        GenAiException.ErrorCode.RESPONSE_GENERATION_ERROR -> "RESPONSE_GENERATION_ERROR"
        GenAiException.ErrorCode.RESPONSE_PROCESSING_ERROR -> "RESPONSE_PROCESSING_ERROR"
        GenAiException.ErrorCode.REQUEST_PROCESSING_ERROR -> "REQUEST_PROCESSING_ERROR"
        GenAiException.ErrorCode.NOT_SUPPORTED -> "NOT_SUPPORTED"
        GenAiException.ErrorCode.PER_APP_BATTERY_USE_QUOTA_EXCEEDED -> "PER_APP_BATTERY_USE_QUOTA_EXCEEDED"
        GenAiException.ErrorCode.BACKGROUND_USE_BLOCKED -> "BACKGROUND_USE_BLOCKED"
        GenAiException.ErrorCode.NOT_ENOUGH_DISK_SPACE -> "NOT_ENOUGH_DISK_SPACE"
        GenAiException.ErrorCode.NEEDS_SYSTEM_UPDATE -> "NEEDS_SYSTEM_UPDATE"
        GenAiException.ErrorCode.AICORE_INCOMPATIBLE -> "AICORE_INCOMPATIBLE"
        else -> "CODE_$c"
    }

    private fun deviceInfo(ctx: Context): JSONObject {
        fun version(pkg: String) = runCatching { ctx.packageManager.getPackageInfo(pkg, 0).versionName ?: "?" }
            .getOrElse { "not found" }
        return JSONObject().put("model", "${Build.MANUFACTURER} ${Build.MODEL}").put("soc", Build.SOC_MODEL)
            .put("android", Build.VERSION.RELEASE).put("sdk", Build.VERSION.SDK_INT)
            .put("security_patch", Build.VERSION.SECURITY_PATCH)
            .put("aicore", version("com.google.android.aicore"))
            .put("play_services", version("com.google.android.gms"))
            .put("private_compute_services", version("com.google.android.as.oss"))
    }

    private fun vitals(ctx: Context): JSONObject {
        val am = ctx.getSystemService(ActivityManager::class.java)
        val mi = ActivityManager.MemoryInfo().also { am?.getMemoryInfo(it) }
        val pm = ctx.getSystemService(PowerManager::class.java)
        return JSONObject().put("battery_c", batteryTempC(ctx)).put("thermal", thermalStatus(ctx))
            .put("headroom_10s", pm?.getThermalHeadroom(10)?.toDouble()?.let { if (it.isNaN()) null else round2(it) })
            .put("avail_mem_mb", mi.availMem / (1024 * 1024)).put("low_memory", mi.lowMemory)
    }

    private fun batteryTempC(ctx: Context): Double? {
        val i: Intent? = ctx.registerReceiver(null, IntentFilter(Intent.ACTION_BATTERY_CHANGED))
        val t = i?.getIntExtra(BatteryManager.EXTRA_TEMPERATURE, Int.MIN_VALUE) ?: Int.MIN_VALUE
        return if (t == Int.MIN_VALUE) null else t / 10.0
    }

    private fun thermalStatus(ctx: Context): Int = ctx.getSystemService(PowerManager::class.java)?.currentThermalStatus ?: -1

