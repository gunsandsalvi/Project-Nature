// B73 writer AI: the phone side (PRE-37, PRE-17, PRE-41, PRE-19; RSK-17, RSK-22).
//
// Runs Kindling's 20 sample prompts (10 hand-made records x 2 voices) through Gemini Nano, the phone's
// built-in model, using ML Kit's GenAI Prompt API. The model runs in Android's AICore service, outside the app.
// Per prompt it reports the time to the first word, words per second, the text and any error. It also reports
// whether the model was available or still downloading, the model's name, and heat and free memory before and
// after. The texts come back in the result so the cloud can run the fact checker on them (checker.py).
//
// Self-contained: one file, prompts embedded (generated by make_prompts.py; don't edit them here).
// Gradle, app module:  implementation("com.google.mlkit:genai-prompt:1.0.0-beta4")   (needs android.useAndroidX=true)
// Call WriterTest.run(context) from a worker thread, with the app in the foreground and the screen on:
// ML Kit refuses to generate for apps in the background. It stops by itself at the time budget (default 4.5 min).
